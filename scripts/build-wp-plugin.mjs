// Builds the WiseUp WordPress plugin into ../wiseup-plugin/wiseup/ and zips it to ../wiseup-plugin/wiseup.zip (upload
// that under Plugins → Add New → Upload Plugin). The plugin is the hand-written code in wp-plugin/ plus what's
// generated from the Astro build: each page's body (generated/pages/*.php), the stylesheets, the site script, every
// asset, and generated/manifest.php (titles, descriptions, per-page CSS/fonts, the theme-restore script).
// Usage: npm run build && node scripts/build-wp-plugin.mjs
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { deflateRawSync, crc32 } from 'node:zlib';
import { DIST, PAGES, sharedCss, pageCss, readPage, rewriteAssetPaths, warnLeftovers, scriptFile, copyAssets } from './wp-shared.mjs';

const OUT_ROOT = path.resolve('..', 'wiseup-plugin');
const OUT = path.join(OUT_ROOT, 'wiseup');
const ASSET_BASE = '<?php echo esc_url( WISEUP_ASSETS ); ?>';
const phpStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const nowdoc = (tag, s) => { if (s.includes(`\n${tag}`)) throw new Error(`nowdoc tag ${tag} appears in its content`); return `<<<'${tag}'\n${s}\n${tag}\n`; };

rmSync(OUT_ROOT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
cpSync('wp-plugin', OUT, { recursive: true });

// ---------- Assets ----------
const assets = path.join(OUT, 'assets');
copyAssets(assets);
// The header's logos under stable names (the build's copies are content-hashed).
const built = readdirSync(path.join(DIST, '_astro'));
for (const [prefix, name] of [['logo', 'wiseup-logo.webp'], ['podcast-logo', 'wiseup-podcast-logo.webp']]) {
  const file = built.find((f) => f.startsWith(`${prefix}.`) && f.endsWith('.webp'));
  if (!file) throw new Error(`dist/_astro/${prefix}.*.webp not found`);
  copyFileSync(path.join(DIST, '_astro', file), path.join(assets, 'brand', name));
}

// ---------- Stylesheets ----------
// The CSS files live in assets/css/, so root-relative url(/fonts/…) and url(/brand/…) become ../fonts/…, ../brand/….
const cssUrls = (css) => css.replace(/url\((['"]?)\/(?!\/)/g, (_, q) => `url(${q}../`);
mkdirSync(path.join(assets, 'css'), { recursive: true });
const shared = cssUrls(sharedCss());
writeFileSync(path.join(assets, 'css', 'wiseup.css'), shared);
const hash = createHash('sha1').update(shared);

// ---------- Pages ----------
// Turns built markup into PHP: literal "<?" can't start PHP, asset paths point into the plugin, and root-relative
// links go through home_url() so the pages also work when WordPress lives in a subfolder.
const toPhp = (slug, html) => {
  let out = rewriteAssetPaths(html.replace(/<\?/g, '&lt;?'), ASSET_BASE);
  warnLeftovers(slug, out);
  return out.replace(/href="\/(?!\/)([^"]*)"/g, (_, rest) => `href="<?php echo esc_url( home_url( ${phpStr('/' + rest.replace(/&amp;/g, '&'))} ) ); ?>"`);
};
mkdirSync(path.join(OUT, 'generated', 'pages'), { recursive: true });
let headScript = null;
const meta = [];
for (const page of PAGES) {
  const b = readPage(page);
  if (!b) throw new Error(`${page.slug} isn't built: run "npm run build" first`);
  const mainStart = b.body.indexOf('<main'), mainEnd = b.body.indexOf('</main>'), footEnd = b.body.indexOf('</footer>');
  if (mainStart < 0 || mainEnd < 0 || footEnd < mainEnd) throw new Error(`${page.slug}: expected header, <main>, then footer in the built body`);
  const main = toPhp(page.slug, b.body.slice(mainStart, mainEnd + 7));
  const lead = toPhp(page.slug, b.body.slice(footEnd + 9).trim()); // the lead popup (LeadModal.astro), per page
  const php = `<?php
// ${page.label} page body, generated by scripts/build-wp-plugin.mjs from dist/${page.distDir}/index.html. Don't edit:
// change the Astro site and rebuild. The header and footer are the plugin's own parts (parts/*.php).
defined( 'ABSPATH' ) || exit;
?>
${main}
<?php if ( wiseup_opt( 'lead_popup' ) ) : ?>
${lead}
<?php endif; ?>
`;
  writeFileSync(path.join(OUT, 'generated', 'pages', `${page.slug}.php`), php);
  hash.update(php);

  const css = ['wiseup.css'];
  const own = pageCss(page);
  if (own) { writeFileSync(path.join(assets, 'css', `${page.slug}.css`), cssUrls(own)); css.push(`${page.slug}.css`); hash.update(own); }
  // Where the header button points on this page (the contact form: /#contact, or #form on the contact page itself).
  const cta = b.body.slice(0, mainStart).match(/class="hd__cta" href="([^"]+)"/)?.[1] || '';
  meta.push({ slug: page.slug, title: b.title, description: b.description, cta, css, extraHead: page.extraHead || '' });

  // The theme-restore script is the same on every page; its default becomes the plugin's "Default mode" setting.
  const script = b.headScript.replace(/const defaultTheme = ("[^"]*"|'[^']*');/, 'const defaultTheme = __WISEUP_DEFAULT_THEME__;');
  if (script === b.headScript) throw new Error('defaultTheme not found in the built head script (Base.astro changed?)');
  headScript ??= script;
}

// ---------- Script + manifest ----------
const js = scriptFile();
hash.update(readFileSync(path.join(DIST, '_astro', js)));
const build = hash.digest('hex').slice(0, 10);
const manifest = `<?php
// Generated by scripts/build-wp-plugin.mjs on ${new Date().toISOString().slice(0, 10)}. Don't edit: rebuild instead.
defined( 'ABSPATH' ) || exit;

return array(
	'build'       => ${phpStr(build)},
	'script'      => ${phpStr(`_astro/${js}`)},
	'head_script' => ${nowdoc('WISEUP_JS', headScript)},
	'pages'       => array(
${meta.map((m) => `		${phpStr(m.slug)} => array(
			'title'       => ${phpStr(m.title)},
			'description' => ${phpStr(m.description)},
			'cta'         => ${phpStr(m.cta)},
			'css'         => array( ${m.css.map(phpStr).join(', ')} ),
			'extra_head'  => ${m.extraHead ? nowdoc('WISEUP_HTML', m.extraHead) : "''"},
		),`).join('\n')}
	),
);
`;
writeFileSync(path.join(OUT, 'generated', 'manifest.php'), manifest);

// ---------- Zip ----------
// Written here rather than with PowerShell's Compress-Archive, which stores Windows backslashes in entry names that
// WordPress's unzip can turn into flat file names.
function zip(dir, outFile) {
  const entries = [];
  const walk = (abs, rel) => {
    for (const name of readdirSync(abs)) {
      const a = path.join(abs, name), r = `${rel}/${name}`;
      statSync(a).isDirectory() ? walk(a, r) : entries.push([a, r]);
    }
  };
  walk(dir, path.basename(dir));
  const now = new Date();
  const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1);
  const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();
  const parts = [], central = [];
  let offset = 0;
  for (const [abs, rel] of entries) {
    const data = readFileSync(abs), name = Buffer.from(rel, 'utf8');
    const deflated = deflateRawSync(data, { level: 9 });
    const store = deflated.length >= data.length;
    const body = store ? data : deflated;
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0); head.writeUInt16LE(20, 4); head.writeUInt16LE(0x0800, 6); head.writeUInt16LE(store ? 0 : 8, 8);
    head.writeUInt16LE(dosTime, 10); head.writeUInt16LE(dosDate, 12); head.writeUInt32LE(crc32(data), 14);
    head.writeUInt32LE(body.length, 18); head.writeUInt32LE(data.length, 22); head.writeUInt16LE(name.length, 26); head.writeUInt16LE(0, 28);
    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0); cen.writeUInt16LE(20, 4); cen.writeUInt16LE(20, 6); cen.writeUInt16LE(0x0800, 8); cen.writeUInt16LE(store ? 0 : 8, 10);
    cen.writeUInt16LE(dosTime, 12); cen.writeUInt16LE(dosDate, 14); cen.writeUInt32LE(crc32(data), 16); cen.writeUInt32LE(body.length, 20);
    cen.writeUInt32LE(data.length, 24); cen.writeUInt16LE(name.length, 28); cen.writeUInt32LE(offset, 42);
    parts.push(head, name, body);
    central.push(cen, name);
    offset += head.length + name.length + body.length;
  }
  const cenSize = central.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cenSize, 12); end.writeUInt32LE(offset, 16);
  writeFileSync(outFile, Buffer.concat([...parts, ...central, end]));
  return entries.length;
}
const zipFile = path.join(OUT_ROOT, 'wiseup.zip');
const count = zip(OUT, zipFile);
console.log(`Built ${OUT} (build ${build})`);
console.log(`Zipped ${count} files to ${zipFile} (${(statSync(zipFile).size / 1048576).toFixed(1)} MB)`);
